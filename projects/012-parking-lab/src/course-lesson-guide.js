/** Describes general completion requirements and model-specific teaching,
 * never an automatic claim that a learner performed or passed an exam task. */
export function getChapterLessonGuide(chapter) {
  const authored = chapter && Object.hasOwn(CHAPTERS, chapter.id) ? CHAPTERS[chapter.id] : null;
  return { ...(authored || chapterGuide(chapter?.objective || '先理解本项目的观察与操作顺序。',
    '依据现场标志、通行条件和实车要求完成操作；本指南不作实考评分。',
    chapter?.action || '先观察，确认条件后再操作。', chapter?.look || '先辨认前方、镜面与周围空间。')),
    briefingText: typeof chapter?.narration === 'string' ? chapter.narration : '' };
}

/** Look -> visible change -> action -> observable completion -> misconception.
 * All mapping uses exact stable IDs, independently of mutable voice wording. */
export function getStepLessonGuide(chapter, step) {
  const chapterId = typeof chapter === 'string' ? chapter : chapter?.id;
  const id = typeof step === 'string' ? step : step?.id;
  const prefix = `${chapterId}:`, stepId = typeof id === 'string' && id.startsWith(prefix) ? id.slice(prefix.length) : id;
  const chapterSteps = Object.hasOwn(STEPS, chapterId) ? STEPS[chapterId] : null;
  const authored = chapterSteps && Object.hasOwn(chapterSteps, stepId) ? chapterSteps[stepId] : null;
  return authored ? { ...authored } : guide(step?.look || '先看前方与周围空间。',
    '先辨认当前道路、车辆姿态和可能的风险。', step?.action || '保持车辆受控，确认任务后再操作。',
    '对照本步目标确认操作效果，再继续下一步。', '未知步骤仅提供通用观察提示，不推断固定点位或实考结果。');
}
